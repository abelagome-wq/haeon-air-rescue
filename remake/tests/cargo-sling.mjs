import assert from 'node:assert/strict';
import * as T from '../vendor/three/three.module.min.js';
import {createCargoSling} from '../src/cargo-sling.js';
import {CARGO_EYE_HEIGHT} from '../src/cargo-container.js';
import {getRotorPerformance} from '../src/rotor-performance.js';

const scene = new T.Scene(), plane = new T.Group();
scene.add(plane);
plane.position.set(0,10,0);
const flight = {object:plane, position:plane.position, state:{id:'SCWZR300', speed:0, grounded:false}};
const city = {
  tileAt(x) {return {groundY:x>70 ? -1 : 0, waterY:x>70 ? 0 : null};},
  flightScenery:{floorAt(x) {return x>=40 && x<60 ? 4 : -Infinity;}}
};
let equipped = true;
const sling = createCargoSling({T,parent:scene,city,flight,equipped:()=>equipped});
const events = [];
const box = sling.register({position:{x:0,y:0,z:0}, massKg:160,
  onAttach(){ events.push('on'); }, onRelease(load, reason){ events.push(reason); }});
const tick = seconds => { for(let i=0; i<Math.ceil(seconds*60); i++) sling.update(1/60); };
const action = () => {const result=sling.begin(); sling.end(); return result;};
const almost = (v,target,margin=.035) => assert.ok(Math.abs(v-target)<margin,`${v} outside ${target} ± ${margin}`);

tick(.1);
assert.equal(action(),false,'must pay out line first');
assert.ok(sling.toggle());
plane.position.x=4;
tick(4);
assert.equal(action(),false,'alignment is required');
plane.position.set(0,24,0);
tick(5);
assert.equal(action(),false,'cannot couple from above cable reach');
plane.position.y=10;
tick(5);
almost(sling.state.hookPosition.y,CARGO_EYE_HEIGHT);
flight.state.verticalSpeed=-3;
assert.equal(action(),false,'cannot attach during fast descent');
flight.state.verticalSpeed=0;
assert.ok(sling.begin());
assert.equal(sling.begin(),false,'holding action does not immediately let go');
sling.end();
assert.equal(sling.state.externalLoadKg,0,'the ground still supports the container');
assert.equal(sling.state.massKg,160);
plane.position.x=1;
tick(1);
almost(box.position.x,0);
assert.ok(sling.toggle());
tick(3);
assert.ok(box.position.y>4);
assert.equal(sling.state.externalLoadKg,160);
assert.ok(getRotorPerformance('SCWZR300',{externalLoadKg:160}).thrustToWeight>1.2);
assert.equal(action(),false,'airborne releases are inhibited');

plane.position.set(30,18,0);
tick(.2);
flight.state.weather={windX:8,windZ:0};
tick(5);
assert.ok(box.position.x>plane.position.x+.12,'load swings downwind');
assert.ok(sling.toggle());
flight.state.weather={};
plane.position.set(77,8,0);
tick(4);
assert.ok(box.grounded);
assert.equal(action(),false,'cannot unload into water');
plane.position.set(50,16,0);
tick(4);
almost(box.position.y,4);
assert.ok(box.grounded);
assert.equal(sling.getAim().y,4.03,'the bridge deck sits above the riverbed');
assert.ok(action());
assert.deepEqual(events,['on','ground']);
assert.ok(action(),'set-down at any dry place can be reattached');
plane.position.set(10,30,0);
tick(1);
assert.equal(sling.state.externalLoadKg,160);
equipped=false;
tick(.2);
assert.equal(sling.state.externalLoadKg,0);
assert.deepEqual(events,['on','ground','on','reset']);
almost(box.position.x,50);
almost(box.position.y,4);
assert.equal(scene.getObjectByName('Cargo winch').visible,false);
equipped=true;
plane.position.set(50,16,0);
tick(.1);
assert.ok(sling.toggle());
tick(4);
assert.ok(action());
assert.ok(action());
box.retire();
assert.ok(scene.getObjectByName('Corrugated cargo container'),'delivered box remains visible');
assert.equal(action(),false,'completed cargo cannot be reattached');
box.dispose();
sling.dispose();
assert.equal(scene.getObjectByName('Corrugated cargo container'),undefined);
assert.equal(scene.getObjectByName('Cargo winch'),undefined);
console.log('Cargo winch pickup, slack, wind, payload, bridge set-down, recovery, cleanup verified.');
